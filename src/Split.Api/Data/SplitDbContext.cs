using Microsoft.EntityFrameworkCore;

namespace Split.Api.Data;

public class SplitDbContext(DbContextOptions<SplitDbContext> options) : DbContext(options)
{
    public DbSet<ExpenseGroup> Groups => Set<ExpenseGroup>();

    public DbSet<Participant> Participants => Set<Participant>();

    public DbSet<Expense> Expenses => Set<Expense>();

    public DbSet<ExpenseShare> ExpenseShares => Set<ExpenseShare>();

    protected override void OnModelCreating(ModelBuilder model)
    {
        // Every entity here generates its own Version 7 GUID at construction, which keeps new
        // rows ordered by creation time in the index instead of scattering them the way random
        // GUIDs do. EF has to be told that, though. Left to its own conventions it assumes a
        // GUID key is generated by the database, so when it meets a new object whose key is
        // already set it concludes the row must exist and issues an UPDATE that matches
        // nothing. Hence ValueGeneratedNever() on each key below.

        model.Entity<ExpenseGroup>(group =>
        {
            group.HasKey(g => g.Id);
            group.Property(g => g.Id).ValueGeneratedNever();
            group.HasIndex(g => g.Slug).IsUnique();
            group.Property(g => g.Slug).HasMaxLength(64);
            group.Property(g => g.Name).HasMaxLength(120);
            group.Property(g => g.Currency).HasMaxLength(3);

            group.HasMany(g => g.Participants)
                 .WithOne()
                 .HasForeignKey(p => p.GroupId)
                 .OnDelete(DeleteBehavior.Cascade);

            group.HasMany(g => g.Expenses)
                 .WithOne()
                 .HasForeignKey(e => e.GroupId)
                 .OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<Participant>(participant =>
        {
            participant.HasKey(p => p.Id);
            participant.Property(p => p.Id).ValueGeneratedNever();
            participant.Property(p => p.Name).HasMaxLength(80);
            participant.HasIndex(p => p.GroupId);
        });

        model.Entity<Expense>(expense =>
        {
            expense.HasKey(e => e.Id);
            expense.Property(e => e.Id).ValueGeneratedNever();
            expense.Property(e => e.Description).HasMaxLength(200);
            expense.HasIndex(e => e.GroupId);

            // Amount is a read-only projection of AmountCents, so EF must not try to map it.
            expense.Ignore(e => e.Amount);

            expense.HasMany(e => e.Shares)
                   .WithOne()
                   .HasForeignKey(s => s.ExpenseId)
                   .OnDelete(DeleteBehavior.Cascade);
        });

        model.Entity<ExpenseShare>(share =>
        {
            share.HasKey(s => s.Id);
            share.Property(s => s.Id).ValueGeneratedNever();
            share.HasIndex(s => s.ExpenseId);
            share.Ignore(s => s.Amount);
        });
    }
}
